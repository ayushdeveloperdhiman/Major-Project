-- =============================================================================
-- CVI Analytical Warehouse - semantic layer (views)  |  MSDS-MAJOR-CVI-001
-- KPI definitions follow the supplied 'Metric Guidance' sheet exactly:
--   Negative Sentiment Rate = negative feedback / total feedback
--   Repeat Purchase Rate    = records with repeat flag / total records
--   Average Resolution Time = mean hours to resolution
--   Revenue at Risk         = revenue of negative-sentiment records
--   Topic Share             = feedback assigned to a topic / total feedback
-- Sentiment used for KPIs = NLP prediction (text-derived); falls back to the
-- reference label only if a record has not been scored yet.
-- This file is generated by cvi.warehouse.render_views() - edit the generator.
-- =============================================================================

DROP VIEW IF EXISTS vw_feedback_360;
CREATE VIEW vw_feedback_360 AS
SELECT
    f.feedback_id, c.customer_id,
    r.region_name, ch.channel_name, ch.channel_type, p.product_category_name,
    i.issue_category, i.issue_theme_group, s.source_name, s.source_class,
    rt.rating_label, f.rating, f.csat_score,
    sr.sentiment_label                                   AS sentiment_ref,
    COALESCE(sp.sentiment_label, sr.sentiment_label)     AS sentiment_pred,
    n.p_negative, n.p_neutral, n.p_positive, n.vader_compound,
    ti.issue_category                                    AS topic_extracted,
    n.nmf_topic_id, n.descriptor, n.negative_descriptor_theme,
    rb.band_label                                        AS resolution_band,
    rb.sla_status,
    rv.tier_label                                        AS revenue_tier,
    seg.segment_name, fs.risk_tier,
    f.customer_revenue_inr, f.order_count, f.repeat_purchase_flag, f.resolution_time_hours,
    f.avg_order_value_inr, f.is_negative_ref, f.sla_breach, f.critical_delay,
    f.flag_repeat_without_orders, f.dq_flags,
    t.feedback_text, t.text_clean
FROM fact_feedback f
JOIN dim_customer          c  ON c.customer_key          = f.customer_key
JOIN dim_region            r  ON r.region_key            = f.region_key
JOIN dim_channel           ch ON ch.channel_key          = f.channel_key
JOIN dim_product_category  p  ON p.product_category_key  = f.product_category_key
JOIN dim_issue             i  ON i.issue_key             = f.issue_key
JOIN dim_feedback_source   s  ON s.source_key            = f.source_key
JOIN dim_rating            rt ON rt.rating_key           = f.rating_key
JOIN dim_sentiment         sr ON sr.sentiment_key        = f.ref_sentiment_key
LEFT JOIN dim_resolution_band rb ON rb.band_key          = f.resolution_band_key
LEFT JOIN dim_revenue_tier    rv ON rv.tier_key          = f.revenue_tier_key
LEFT JOIN feedback_text       t  ON t.feedback_id        = f.feedback_id
LEFT JOIN fact_feedback_nlp   n  ON n.feedback_id        = f.feedback_id
LEFT JOIN dim_sentiment       sp ON sp.sentiment_key     = n.pred_sentiment_key
LEFT JOIN dim_issue           ti ON ti.issue_key         = n.topic_issue_key
LEFT JOIN fact_feedback_segment fs ON fs.feedback_id     = f.feedback_id
LEFT JOIN dim_segment         seg ON seg.segment_key     = fs.segment_key;

DROP VIEW IF EXISTS vw_kpi_overall;
CREATE VIEW vw_kpi_overall AS
SELECT
    COUNT(*)                                                                          AS feedback_count,
    ROUND(AVG(CASE WHEN sentiment_pred = 'Negative' THEN 1.0 ELSE 0.0 END), 4)        AS negative_sentiment_rate,
    ROUND(AVG(CASE WHEN sentiment_pred = 'Positive' THEN 1.0 ELSE 0.0 END), 4)        AS positive_sentiment_rate,
    ROUND(100.0 * (AVG(CASE WHEN sentiment_pred = 'Positive' THEN 1.0 ELSE 0.0 END)
                 - AVG(CASE WHEN sentiment_pred = 'Negative' THEN 1.0 ELSE 0.0 END)), 2) AS net_sentiment_score,
    ROUND(AVG(CAST(repeat_purchase_flag AS REAL)), 4)                                 AS repeat_purchase_rate,
    ROUND(AVG(resolution_time_hours), 3)                                              AS avg_resolution_hours,
    ROUND(AVG(csat_score), 3)                                                         AS avg_csat,
    ROUND(AVG(rating), 3)                                                             AS avg_rating,
    ROUND(SUM(customer_revenue_inr), 2)                                               AS total_revenue_inr,
    ROUND(SUM(CASE WHEN sentiment_pred = 'Negative' THEN customer_revenue_inr ELSE 0 END), 2) AS revenue_at_risk_inr
FROM vw_feedback_360;

